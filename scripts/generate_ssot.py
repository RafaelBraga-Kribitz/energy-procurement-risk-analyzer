"""Generate reports/NUMERIC_SSOT.md — the ONLY source of quoted numbers (GV-301).

Collects the tagged rows every producer wrote to ``data/processed/ssot/*.csv``
(profile, analytics, strategies — never recomputed here) into one markdown
table ``key | value | unit | tag | produced_by | updated_at``, then checks:

- GV-302: the minimum key set is present;
- E-2: a VERIFIED row may only come from a VERIFIED-only producer (analytics),
  never from anything that touched the CALIBRATED load profile;
- freshness (SPEC-08 §4): the sha256 of every committed results CSV is embedded,
  so ``check_ssot_consistency.py`` can detect an SSOT older than its results.

A fixture run (ADR-018) gets the FIXTURE banner at the top.

Implements: GV-301, GV-302, E-2, E-3, SPEC-08 §4 freshness.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from collections.abc import Sequence
from datetime import date
from pathlib import Path

import pandas as pd

from epra.common.config import REPO_ROOT, Settings, load_settings, load_strategy_config
from epra.common.provenance import banner_lines
from epra.common.ssot import read_ssot_rows

SSOT_PATH = REPO_ROOT / "reports" / "NUMERIC_SSOT.md"
#: Results artifacts whose content the SSOT must be at least as new as.
RESULT_GLOBS = ("reports/strategies/*.csv", "reports/analytics/*.csv")
VERIFIED_PRODUCERS = ("analytics/",)
DIGEST_PREFIX = "<!-- results-digest "


def required_keys(years: Sequence[int], strategies: Sequence[str]) -> list[str]:
    """GV-302 minimum key set for the configured years and strategy grid.

    Implements: GV-302.
    """
    keys = [
        "wrong_strategy_cost_total",
        "best_strategy_5yr",
        "p_ref_base",
        "p_ref_peak",
        "oespi_base_ref",
        "consumer_peak_share",
        "garch_persistence",
        "data_last_month",
    ]
    keys += [f"wrong_strategy_cost_{y}" for y in years]
    keys += [f"cost_{s}_{y}" for s in strategies for y in years]
    keys += [f"p95_next12m_{s}" for s in strategies]
    keys += [f"cvar95_next12m_{s}" for s in strategies]
    keys += [f"{k}_{y}" for k in ("annual_mean_price", "neg_hours", "spread_mean") for y in years]
    return keys


def results_digest(root: Path = REPO_ROOT) -> str:
    """sha256 over the committed results CSVs (sorted paths + bytes, LF line endings).

    CRLF is normalised to LF first: a Windows checkout (core.autocrlf) holds the
    CSVs with CRLF while git and CI hold LF, and the digest must not depend on
    the platform that ran ``make ssot`` (A-4).
    """
    digest = hashlib.sha256()
    for pattern in RESULT_GLOBS:
        for path in sorted(root.glob(pattern)):
            digest.update(path.relative_to(root).as_posix().encode())
            digest.update(path.read_bytes().replace(b"\r\n", b"\n"))
    return digest.hexdigest()


def validate(rows: pd.DataFrame, years: Sequence[int], strategies: Sequence[str]) -> list[str]:
    """GV-302 + E-2 problems; empty = valid."""
    problems = [
        f"missing GV-302 key: {k}"
        for k in required_keys(years, strategies)
        if k not in set(rows["key"])
    ]
    verified = rows[rows["tag"] == "VERIFIED"]
    bad = verified[~verified["produced_by"].str.startswith(VERIFIED_PRODUCERS)]
    problems += [f"E-2: VERIFIED row {k} from non-VERIFIED producer" for k in bad["key"]]
    return problems


def render(rows: pd.DataFrame, settings: Settings, updated: str, digest: str) -> str:
    """The NUMERIC_SSOT.md text (GV-301 table format)."""
    lines = [
        "# NUMERIC SSOT",
        "",
        "Auto-generated by `scripts/generate_ssot.py` (`make ssot`) — do not edit by hand. "
        "This table is the only permitted source for numbers quoted in README.md and "
        "reports/EXEC_SUMMARY.md (Charter E-3, SPEC-08 GV-301/303).",
        "",
        *banner_lines(settings),
        "| key | value | unit | tag | produced_by | updated_at |",
        "|---|---:|---|---|---|---|",
    ]
    lines += [
        f"| {r.key} | {r.value} | {r.unit} | {r.tag} | {r.produced_by} | {updated} |"
        for r in rows.itertuples(index=False)
    ]
    lines += ["", f"{DIGEST_PREFIX}{digest} -->", ""]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    """Write the SSOT; exit 1 on a GV-302/E-2 problem.

    Implements: GV-301, GV-302, E-2.
    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--output", type=Path, default=SSOT_PATH)
    parser.add_argument(
        "--updated", default=date.today().isoformat(), help="updated_at stamp (default: today)"
    )
    args = parser.parse_args(argv)
    settings = load_settings()
    cfg = load_strategy_config()
    rows = read_ssot_rows(settings)
    strategies = ["S1", "S2", "S3", *(f"S4_{round(h * 100)}" for h in cfg.hybrid_ratios)]
    problems = validate(rows, cfg.retrospective_years, strategies)
    for problem in problems:
        print(f"ERROR: {problem}", file=sys.stderr)
    if problems:
        return 1
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(rows, settings, args.updated, results_digest()), encoding="utf-8")
    print(f"OK: {len(rows)} SSOT rows -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
